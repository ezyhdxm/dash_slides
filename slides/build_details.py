"""Build the appendix of component code slides in index.html from demos/components/*.py.

Each card on slides 6 and 7 has data-detail="<script name>". Clicking it opens that script's slide: the code on the
left (step 1 highlights the component, step 2 the callback that reads its value) and the card's animation on the
right. The slides go between the DETAILS markers, so re-run this after changing a script or a card:

    python slides/build_details.py
"""
import html
import re
from pathlib import Path

HERE = Path(__file__).parent
COMPONENTS = HERE.parent / "demos" / "components"
PAGE = HERE / "index.html"
BEGIN, END = "<!-- DETAILS:BEGIN (generated by build_details.py) -->", "<!-- DETAILS:END -->"

# the calls that make the component, per script: step 1 highlights each call through its closing bracket
CALLS = {
    "g1_click": ["dcc.Graph("], "g2_hover": ["dcc.Graph("],
    "g3_select": ["dcc.Graph(", "fig.update_layout("], "g4_relayout": ["dcc.Graph("],
    "w1_dropdown": ["dcc.Dropdown("], "w2_checklist_radio": ["dcc.Checklist(", "dcc.RadioItems("],
    "w3_slider": ["dcc.Slider(", "dcc.RangeSlider("], "w4_input": ["dcc.Input("],
    "w5_dates": ["dcc.DatePickerSingle(", "dcc.DatePickerRange("], "w6_tabs": ["dcc.Tabs("],
    "w7_button": ["html.Button("], "w8_interval": ["dcc.Interval("],
    "w9_store_files": ["dcc.Upload(", "dcc.Store(", "dcc.Download("],
}


def block(lines, start):
    """Line numbers (1-based) from `start` to where its brackets close."""
    depth, i = 0, start
    while True:
        depth += lines[i].count("(") + lines[i].count("[") - lines[i].count(")") - lines[i].count("]")
        if depth <= 0:
            return list(range(start + 1, i + 2))
        i += 1


def ranges(nums):
    nums, out = sorted(set(nums)), []
    for n in nums:
        if out and n == out[-1][1] + 1:
            out[-1][1] = n
        else:
            out.append([n, n])
    return ",".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)


def steps(name, lines):
    comp = []
    for call in CALLS[name]:
        comp += block(lines, next(i for i, l in enumerate(lines) if call in l and "Output(" not in l))
    reads = []                                                             # each @app.callback(...) in full
    for i, l in enumerate(lines):
        if l.startswith("@app.callback("):
            reads += block(lines, i)
    if sum("@app.callback" in l for l in lines) == 1:   # one callback: add its body
        d = next(i for i, l in enumerate(lines) if l.startswith("def "))
        e = next(i for i in range(d, len(lines)) if not lines[i].strip())
        reads += range(d + 1, e + 1)
    return f"{ranges(comp)}|{ranges(reads)}"


def card(page, name):
    m = re.search(rf'class="fcard[^"]*" data-detail="{name}"[^>]*>(.*?)<div class="what">(.*?)</div>\s*<div class="name">(.*?)</div>', page, re.S)
    svg = re.sub(r'id="(clp\w+)"', r'id="\1-d"', m.group(1).strip())
    svg = re.sub(r"url\(#(clp\w+)\)", r"url(#\1-d)", svg)
    return svg, m.group(2), m.group(3)


def graph_title(name, title):
    return f"dcc.Graph · {title}" if name.startswith("g") else title


def slide(page, name):
    src = (COMPONENTS / f"{name}.py").read_text().rstrip("\n")
    lines = src.split("\n")
    svg, what, title = card(page, name)
    title = graph_title(name, title)
    small = " small-code" if len(lines) > 25 else ""
    return f"""<section class="detail" id="d-{name}" data-visibility="uncounted">
  <div class="kicker">Component code</div>
  <div style="position:relative"><h2>{title}</h2>
    <button class="back-btn" data-detail="{name}">← Back</button></div>
  <div class="cols detail-cols">
    <div>
<pre class="{small.strip()}"><code class="language-python" data-trim data-line-numbers="{steps(name, lines)}">
{html.escape(src)}
</code></pre>
    </div>
    <div>
      <div class="fcard big">{svg}
        <div class="what">{what}</div></div>
      <p class="legend"><span class="k">1</span> the component &nbsp; <span class="k">2</span> the callback that reads its value
        <br>(→ moves from 1 to 2)</p>
      <div class="run">Try it: python demos/components/{name}.py</div>
    </div>
  </div>
</section>
"""


def main():
    page = PAGE.read_text()
    names = re.findall(r'class="fcard[^"]*" data-detail="(\w+)"', page)
    links = "\n".join(f'      <li><a href="#/d-{n}">{graph_title(n, card(page, n)[2])}</a></li>' for n in names)
    body = "\n".join([f"""<section class="detail" id="appendix" data-visibility="uncounted">
  <div class="kicker">Appendix</div>
  <h2>Component code</h2>
  <p class="small muted">One small, runnable app per card on slides 6 and 7. Click a card in the talk to open its
    slide; <b>← Back</b> returns to where you were.</p>
  <ol class="detail-index">
{links}
  </ol>
</section>
"""] + [slide(page, n) for n in names])
    a, b = page.index(BEGIN) + len(BEGIN), page.index(END)
    PAGE.write_text(page[:a] + "\n" + body + page[b:])
    print(f"{len(names)} component slides written")


if __name__ == "__main__":
    main()
